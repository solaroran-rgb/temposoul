#!/usr/bin/env node
/**
 * names 域 codegen：@temposoul/core/onomastics 全量字表 -> 骨架
 * 全量字表导出名未确认（契约缺口）时，打印警告并保留现有种子集，不覆盖。
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function main() {
  let onomastics = null;
  try {
    onomastics = await import('@temposoul/core/onomastics');
  } catch (err) {
    console.warn(`[gen-names-skeleton] 无法加载 onomastics：${String(err)}`);
  }

  const chars = onomastics?.CHAR_DOSSIERS ?? [];
  if (!Array.isArray(chars) || chars.length === 0) {
    console.warn(
      '[gen-names-skeleton] 未取到全量字表（CHAR_DOSSIERS），保留 src/data/names/generated/skeletons.ts 种子集'
    );
    return;
  }

  const rows = chars
    .map((c, i) => {
      const char = JSON.stringify(c.char);
      const strokes = Number(c.kangxiStrokes ?? 0);
      return `  { id: ${char}, slug: ${char}, title: ${char}, category: ${JSON.stringify(
        c.wuxing ?? 'unknown'
      )}, order: ${i}, engineRef: makeEngineRef('@temposoul/core/onomastics#CharDossierLike', { char: ${char}, kangxiStrokes: ${strokes} }), domainFields: { pinyin: ${JSON.stringify(
        c.pinyin ?? ''
      )}, kangxiStrokes: ${strokes}, radical: ${JSON.stringify(c.radical ?? '')}, wuxing: ${JSON.stringify(
        c.wuxing ?? ''
      )}, rareCharLevel: ${JSON.stringify(c.rareCharLevel ?? 'common')} } },`;
    })
    .join('\n');

  const body = `// @generated by scripts/gen-names-skeleton.mjs — DO NOT EDIT
// domain: names
// source: @temposoul/core/onomastics#CharDossierLike

import type { ContentSkeleton } from '@/data/content/types';
import { makeEngineRef } from '@/data/content/fingerprint';

export const NAME_CHAR_SKELETONS: ContentSkeleton[] = [
${rows}
];
`;

  const out = resolve(ROOT, 'src/data/names/generated/skeletons.ts');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body, 'utf8');
  console.log(`[gen-names-skeleton] names skeletons: ${chars.length} -> ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
