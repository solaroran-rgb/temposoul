const LIBRARY: string[][] = buildLibrary();

/** 查库：hexagramIdx×categoryIdx → 话术；未命中走组合兜底 */
export function lookupReading(hexagramName: string, category: LiuyaoCategory): string {
  const hi = TOP20_HEXAGRAMS.indexOf(hexagramName);
  const ci = CATEGORIES.indexOf(category);
  if (hi >= 0 && ci >= 0) {
    return LIBRARY[hi][ci];
  }
  return composeGeneric(hexagramName, category);
}

/** 四段式组装（象/势/行/免责） */
export function assembleSections(
  hexagramName: string,
  category: LiuyaoCategory,
): { part: '象' | '势' | '行' | '免责'; text: string }[] {
  const reading = lookupReading(hexagramName, category);
  return [
    { part: '象', text: `本卦为「${hexagramName}」，传统视角呈现其整体状态。` },
    { part: '势', text: `就${CATEGORY_LABEL[category]}而言：${reading}` },
    { part: '行', text: '生活层面建议：以从容心态处理，重要决定多结合现实情况判断。' },
    { part: '免责', text: LIUYAO_DISCLAIMER },
  ];
}
