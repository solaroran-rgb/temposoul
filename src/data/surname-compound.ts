/** 按最长匹配原则切分姓名：优先双字姓，其次单字姓。 */
export function splitHanName(name: string): { surname: string; given: string } {
  if (name.length >= 2 && COMPOUND_SURNAMES.includes(name.slice(0, 2))) {
    return { surname: name.slice(0, 2), given: name.slice(2) };
  }
  return { surname: name.slice(0, 1), given: name.slice(1) };
}
