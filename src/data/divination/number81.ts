export interface NumberFortuneResult {
  raw: string;
  digitSeq: string;
  tail: string;
  number: number;
  entry: NumberFortuneEntry;
  complete: boolean;
}

/** 确定性归约：清洗 → 字母转数 → 取末四位 → 除 81 取余（余 0 记 81） */
export function calcNumberFortune(raw: string): NumberFortuneResult {
  const cleaned = raw.toUpperCase().replace(/[^0-9A-Z]/g, '');
  let seq = '';
  for (const ch of cleaned) {
    if (/[0-9]/.test(ch)) seq += ch;
    else seq += String(ch.charCodeAt(0) - 64);
  }
  const tail = seq.slice(-4);
  const value = tail === '' ? 0 : Number(tail);
  const remainder = value % 81;
  const number = remainder === 0 ? 81 : remainder;
  const entry = NUMBER_81_TABLE.find((e) => e.n === number) as NumberFortuneEntry;
  return { raw, digitSeq: seq, tail, number, entry, complete: Boolean(entry.text) };
}
