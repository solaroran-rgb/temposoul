/**
 * landmarks.ts —— 地理引擎地标数据层（POC：台北）
 *
 * 数据原则（对应用户架构「真实位置数据 + 真实地理数据 + 程序化渲染」）：
 *   - 地标为真实经纬度（公开可查的地理坐标，近似到 ~100m 级）
 *   - 轮廓环为「示意级」简化多边形（POC 用；正式版将该接口替换为 OSM way 数据解析，
 *     管线（geoEngine）只消费 Landmark[] 数组，不感知数据来源）
 *   - 类型：building / tower / park / mountain / river / road
 *
 * 范围：台北市中心 25.02–25.11°N, 121.49–121.58°E（覆盖市区主要地标、两河、主干道、象山）
 */
export type LandmarkKind = 'building' | 'tower' | 'park' | 'mountain' | 'river' | 'road';

export interface Landmark {
  id: string;
  name: string;
  kind: LandmarkKind;
  lat: number; // 中心纬度（°N）
  lon: number; // 中心经度（°E）
  heightM?: number; // 相对地面高度（建筑顶/塔尖，米）
  ring?: [number, number][]; // 轮廓环（经纬度，闭合；示意级）
  polyline?: [number, number][]; // 多段线（河流/道路/山脊，经纬度）
  warm?: boolean; // 暖橙焦点（默认仅 101 塔尖）
}

/** 经纬度→米（局部平面近似；POC 用，正式版接投影库） */
export const DEG_LAT_M = 110574;
export function degLonM(lat: number): number {
  return 111320 * Math.cos((lat * Math.PI) / 180);
}

